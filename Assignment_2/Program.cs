    public class Employee
    {
        public string? name;
        public string? Name
        {
            set
            {
                if (value != null)
                    name = value;
                else
                    Console.WriteLine("Enter Proper Name");
            }
            get
            {
                return name;
            }
        }
        public static int empNo = 0;
        public int EmpNo 
        { 
            get 
            { 
                return empNo;
            }
        }

        public decimal basic;
        public decimal Basic
        {
            set
            {
                if(value >=25000 && value <=500000)
                    basic = value;
                else
                    Console.WriteLine("Basic Salary Must be in Range");
            }
            get
            {
                return basic;
            }
        }
        public short deptNo;
        public short DeptNo
        {
            set
            {
                if(value > 0)
                    deptNo = value;
                else
                    Console.WriteLine("Dept No Must be Greater than 0");
            }
            get
            {
                return deptNo;
            }
        }
        public void GetNetSalary()
        {
            decimal netSalary = basic + (basic * 0.12m) + (basic * 0.08m);
            Console.WriteLine($"Net Salary is : {netSalary}");
        }

        public Employee(string name="Parshuram",decimal basic = 50000,short deptno = 10)
